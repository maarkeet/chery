create or replace function public.is_store_admin()
returns boolean
language sql
stable
security definer
set search_path = pg_catalog, pg_temp
as $$
    select exists (
        select 1
        from public.store_admins
        where user_id = auth.uid()
    );
$$;

create or replace function public.save_store_state(
    p_catalog jsonb,
    p_categories jsonb,
    p_announcements jsonb,
    p_display jsonb
)
returns void
language plpgsql
security definer
set search_path = pg_catalog, pg_temp
as $$
declare
    v_product jsonb;
    v_category jsonb;
    v_ids bigint[] := array[]::bigint[];
    v_slugs text[] := array[]::text[];
    v_id bigint;
    v_slug text;
begin
    if not public.is_store_admin() then
        raise exception 'Store administrator access is required';
    end if;
    if jsonb_typeof(p_catalog) is distinct from 'array'
        or jsonb_typeof(p_categories) is distinct from 'array'
        or jsonb_typeof(p_announcements) is distinct from 'array'
        or jsonb_typeof(p_display) is distinct from 'object' then
        raise exception 'Invalid store data';
    end if;
    if exists (
        select 1
        from jsonb_array_elements_text(p_announcements) as announcement_entry(text)
        where announcement_entry.text ~* '(شحن|توصيل|استلام|shipping|delivery)'
    ) or coalesce(p_display->>'shopHeading', '') ~* '(شحن|توصيل|استلام|shipping|delivery)'
        or coalesce(p_display->>'heroSubtitle', '') ~* '(شحن|توصيل|استلام|shipping|delivery)' then
        raise exception 'Unsupported store content';
    end if;

    insert into public.categories (slug, name, sort_order)
    values ('all', 'الكل', 0)
    on conflict (slug) do nothing;

    for v_category in select value from jsonb_array_elements(p_categories) as entries(value)
    loop
        v_slug := v_category->>'slug';
        if v_slug is null or v_slug !~ '^[a-z0-9][a-z0-9_-]*$' then
            raise exception 'Invalid category';
        end if;
        insert into public.categories (slug, name, name_en, image_url, sort_order)
        values (
            v_slug,
            coalesce(nullif(v_category->>'name', ''), v_slug),
            nullif(v_category->>'nameEn', ''),
            coalesce(nullif(v_category->>'imageUrl', ''), ''),
            coalesce(nullif(v_category->>'sortOrder', '')::integer, 0)
        )
        on conflict (slug) do update set
            name = excluded.name,
            name_en = excluded.name_en,
            image_url = excluded.image_url,
            sort_order = excluded.sort_order;
        v_slugs := array_append(v_slugs, v_slug);
    end loop;
    if not ('all' = any(v_slugs)) then
        v_slugs := array_append(v_slugs, 'all');
    end if;

    for v_product in select value from jsonb_array_elements(p_catalog) as entries(value)
    loop
        begin
            v_id := (v_product->>'id')::bigint;
        exception when others then
            raise exception 'Invalid product id';
        end;

        insert into public.products (
            id, title, title_en, category, vendor, description, price,
            compare_at, badge, has_colors, sizes, variants, active
        )
        values (
            v_id,
            coalesce(nullif(v_product->>'title', ''), 'منتج بدون اسم'),
            coalesce(v_product->>'title_en', ''),
            coalesce(nullif(v_product->>'category', ''), 'all'),
            coalesce(nullif(v_product->>'vendor', ''), 'Cherie Mommy'),
            coalesce(v_product->>'description', ''),
            coalesce(nullif(v_product->>'price', '')::numeric, 0),
            nullif(v_product->>'compare_at', '')::numeric,
            nullif(v_product->>'badge', ''),
            coalesce((v_product->>'has_colors')::boolean, false),
            coalesce(v_product->'sizes', '[]'::jsonb),
            coalesce(v_product->'variants', '[{"name":"","hex":"#F2B6C6","img":""}]'::jsonb),
            coalesce((v_product->>'active')::boolean, true)
        )
        on conflict (id) do update set
            title = excluded.title,
            title_en = excluded.title_en,
            category = excluded.category,
            vendor = excluded.vendor,
            description = excluded.description,
            price = excluded.price,
            compare_at = excluded.compare_at,
            badge = excluded.badge,
            has_colors = excluded.has_colors,
            sizes = excluded.sizes,
            variants = excluded.variants,
            active = excluded.active,
            updated_at = now();

        insert into public.product_private_data (
            product_id, purchase_price, unit, unit_factor, stock
        )
        values (
            v_id,
            coalesce(nullif(v_product->>'purchase_price', '')::numeric, 0),
            coalesce(nullif(v_product->>'unit', ''), 'قطعة'),
            coalesce(nullif(v_product->>'unit_factor', '')::numeric, 1),
            coalesce(nullif(v_product->>'stock', '')::integer, 0)
        )
        on conflict (product_id) do update set
            purchase_price = excluded.purchase_price,
            unit = excluded.unit,
            unit_factor = excluded.unit_factor,
            stock = excluded.stock,
            updated_at = now();

        v_ids := array_append(v_ids, v_id);
    end loop;

    delete from public.products where not (id = any(v_ids));
    delete from public.categories
    where slug <> 'all' and not (slug = any(v_slugs));

    insert into public.store_settings (key, value)
    values
        ('announcements', p_announcements),
        ('display', p_display)
    on conflict (key) do update set
        value = excluded.value,
        updated_at = now();
end;
$$;

create or replace function public.submit_store_order(
    p_customer_name text,
    p_customer_phone text,
    p_customer_address text,
    p_items jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, pg_temp
as $$
declare
    v_item jsonb;
    v_product public.products%rowtype;
    v_product_id bigint;
    v_qty integer;
    v_variant_name text;
    v_size text;
    v_image text;
    v_items jsonb := '[]'::jsonb;
    v_subtotal numeric(12, 2) := 0;
    v_order_id bigint;
    v_order_number text;
begin
    if length(trim(coalesce(p_customer_name, ''))) not between 2 and 120
        or length(trim(coalesce(p_customer_phone, ''))) not between 8 and 32
        or length(trim(coalesce(p_customer_address, ''))) not between 8 and 500 then
        raise exception 'Please provide valid customer details';
    end if;

    if jsonb_typeof(p_items) is distinct from 'array' then
        raise exception 'Invalid order items';
    end if;
    if jsonb_array_length(p_items) < 1 or jsonb_array_length(p_items) > 50 then
        raise exception 'Invalid order items';
    end if;

    for v_item in select value from jsonb_array_elements(p_items) as entries(value)
    loop
        if jsonb_typeof(v_item) is distinct from 'object' then
            raise exception 'Invalid order item';
        end if;

        begin
            v_product_id := (v_item->>'id')::bigint;
            v_qty := (v_item->>'qty')::integer;
        exception when others then
            raise exception 'Invalid product or quantity';
        end;

        if v_qty < 1 or v_qty > 99 then
            raise exception 'Invalid product quantity';
        end if;

        select * into v_product
        from public.products
        where id = v_product_id and active = true;

        if not found then
            raise exception 'A product in this order is unavailable';
        end if;

        v_variant_name := coalesce(v_item->>'variantName', '');
        v_size := nullif(trim(coalesce(v_item->>'size', '')), '');

        if v_product.has_colors and not exists (
            select 1
            from jsonb_array_elements(v_product.variants) as variant(value)
            where coalesce(value->>'name', '') = v_variant_name
        ) then
            raise exception 'A selected product color is unavailable';
        end if;

        if jsonb_array_length(v_product.sizes) > 0
            and (v_size is null or not (v_product.sizes @> jsonb_build_array(v_size))) then
            raise exception 'A selected product size is unavailable';
        end if;

        if jsonb_array_length(v_product.sizes) = 0 then
            v_size := null;
        end if;

        select coalesce(value->>'img', '')
        into v_image
        from jsonb_array_elements(v_product.variants) as variant(value)
        where coalesce(value->>'name', '') = v_variant_name
        limit 1;

        v_subtotal := v_subtotal + (v_product.price * v_qty);
        v_items := v_items || jsonb_build_array(jsonb_build_object(
            'id', v_product.id,
            'title', v_product.title,
            'variantName', v_variant_name,
            'size', v_size,
            'price', v_product.price,
            'qty', v_qty,
            'img', coalesce(v_image, '')
        ));
    end loop;

    insert into public.orders (
        customer_name,
        customer_phone,
        customer_address,
        items,
        subtotal,
        total,
        status
    )
    values (
        trim(p_customer_name),
        trim(p_customer_phone),
        trim(p_customer_address),
        v_items,
        v_subtotal,
        v_subtotal,
        'new'
    )
    returning id into v_order_id;

    v_order_number := 'CM-' || lpad(v_order_id::text, 6, '0');
    update public.orders
    set order_number = v_order_number
    where id = v_order_id;

    return jsonb_build_object(
        'id', v_order_id,
        'order_number', v_order_number,
        'total', v_subtotal
    );
end;
$$;

